// Детерминированный генератор, чтобы объявления не менялись при перезагрузке
function mulberry32(a) {
  return function () {
    a |= 0; a = a + 0x6D2B79F5 | 0;
    let t = Math.imul(a ^ a >>> 15, 1 | a);
    t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t;
    return ((t ^ t >>> 14) >>> 0) / 4294967296;
  };
}

function generateListings(n) {
  const rnd = mulberry32(2026);
  const pick = arr => arr[Math.floor(rnd() * arr.length)];
  const brandNames = Object.keys(BRANDS);
  const weights = { Toyota: 6, Lexus: 3, Honda: 4, Mercedes: 3, Hyundai: 3, Kia: 2, Subaru: 2, Mitsubishi: 2, BYD: 2 };
  const pool = brandNames.flatMap(b => Array(weights[b] || 1).fill(b));
  const colorNames = Object.keys(COLORS);
  const now = Date.now();
  const list = [];

  for (let i = 0; i < n; i++) {
    const brand = pick(pool);
    const [model, body, minP, maxP, yFrom, vol, fuelDef] = pick(BRANDS[brand].m);
    const year = Math.min(2026, yFrom + Math.floor(rnd() * (2026 - yFrom + 1)));
    const age = (year - yFrom) / Math.max(1, 2026 - yFrom);
    let price = minP + (maxP - minP) * (age * 0.75 + rnd() * 0.25);
    price = Math.round(price / 100) * 100;
    const mileage = year >= 2025 ? Math.floor(rnd() * 15) * 1000 : Math.round(((2026 - year) * (9000 + rnd() * 16000)) / 1000) * 1000;
    const fuel = fuelDef || (rnd() < 0.12 ? 'Газ/бензин' : rnd() < 0.15 ? 'Дизель' : 'Бензин');
    const japanese = ['Toyota', 'Honda', 'Mitsubishi', 'Subaru', 'Nissan'].includes(brand);
    const wheel = japanese && rnd() < 0.35 ? 'Правый' : 'Левый';
    const gear = fuel === 'Электро' ? 'Автомат' : brand === 'Lada' && rnd() < 0.7 ? 'Механика' : model === 'Prius' || model === 'Fit' ? 'Вариатор' : rnd() < 0.85 ? 'Автомат' : 'Механика';
    const drive = ['Внедорожник', 'Пикап'].includes(body) || rnd() < (body === 'Кроссовер' ? 0.6 : 0.12) ? 'Полный' : brand === 'BMW' || brand === 'Mercedes' ? 'Задний' : 'Передний';
    const color = pick(colorNames);
    const seller = pick(SELLERS);
    list.push({
      id: 100000 + i,
      brand, model, body, year, price, mileage, fuel, wheel, gear, drive, color,
      engine: fuel === 'Электро' ? 0 : vol,
      hp: fuel === 'Электро' ? 200 + Math.floor(rnd() * 350) : Math.round(vol * (60 + rnd() * 25)),
      city: rnd() < 0.55 ? 'Бишкек' : rnd() < 0.4 ? 'Ош' : pick(CITIES),
      cleared: rnd() < 0.82,
      exchange: rnd() < 0.3,
      photos: 3 + Math.floor(rnd() * 18),
      top: rnd() < 0.08,
      views: 40 + Math.floor(rnd() * 3000),
      created: now - Math.floor(rnd() * 14 * 24 * 3600 * 1000),
      desc: pick(DESCS),
      seller,
      dealer: seller.startsWith('Автосалон'),
      phone: `+996 ${pick(['555', '700', '707', '772', '777', '550', '999'])} ${String(100 + Math.floor(rnd() * 900))} ${String(100 + Math.floor(rnd() * 900))}`,
      market: rnd()
    });
  }
  return list;
}
